package com.rays.basic;

public class Swapingtwo {
	public static void main(String[] args) {
		
		int a = 20;
		int b = 25;
		
		System.out.println(" a = " + a);
		System.out.println(" b = " + b);
		
		System.out.println("---------");
		//swaping
		
		
		a = a+b; // a = 45;
		b = a-b; // b = 25;
		a = a-b; // a =20;
		
		System.out.println(" a = " + a);
		System.out.println(" b = " + b);
	}
	

}
